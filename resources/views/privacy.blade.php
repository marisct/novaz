    <h1>Privacy Policy</h1>
    <p class="updated">Last updated: 10 November 2026 &middot; Applies to the website <strong>novaz.in</strong> and the <strong>NOVA Z</strong> Android app (package <code>in.novaz.app</code>).</p>

    <p>NOVA Z Institute ("NOVA Z", "we") runs a learning portal for students preparing for central government competitive exams and bank exams. This page explains what information we hold about you, why we hold it, and the choices you have. We follow India's Digital Personal Data Protection Act, 2023.</p>

    <h2>1. Who can use the app</h2>
    <p>Accounts are created by the institute for its enrolled students, teachers and staff. You cannot sign up on your own, and the app is not directed at children under 13. If a student is under 18, the institute collects the information with the consent of a parent or guardian at the time of admission.</p>

    <h2>2. Information we collect</h2>
    <table>
        <thead><tr><th>Information</th><th>Why we need it</th></tr></thead>
        <tbody>
        <tr><td>Name, email address, mobile number, admission number, date of birth, gender, address</td><td>To create your account, identify you, and contact you about your course</td></tr>
        <tr><td>Parent or guardian name and mobile number (students only)</td><td>To share attendance and progress with your family, where the institute offers this</td></tr>
        <tr><td>Course, batch and attendance records</td><td>To run your classes and show your attendance percentage</td></tr>
        <tr><td>Your answers, scores, time taken and rankings in practice tests</td><td>To show your results, subject-wise performance and progress</td></tr>
        <tr><td>Study material downloads and sign-in times</td><td>To keep your account secure and to understand which materials are used</td></tr>
        <tr><td>Technical data: device type, app version, IP address, error logs</td><td>To keep the service running and fix problems</td></tr>
        </tbody>
    </table>
    <p>We do <strong>not</strong> collect your precise location, contacts, photos, files, payment card details or government ID numbers through the app. The app does not show advertisements and does not use advertising or analytics trackers.</p>

    <h2>3. How we use the information</h2>
    <ul>
        <li>Providing the courses, tests, study materials and results you signed up for</li>
        <li>Letting your teachers and the institute's administrators see your attendance and performance</li>
        <li>Sending you notices about classes, tests and results (by the app, email or SMS)</li>
        <li>Keeping the service secure and preventing misuse</li>
    </ul>
    <p>We never sell your information and we do not use it for advertising.</p>

    <h2>4. Who can see your information</h2>
    <ul>
        <li><strong>You</strong>, in the app and on the website after signing in</li>
        <li><strong>Your teachers and the institute's staff</strong>, for the courses you are enrolled in</li>
        <li><strong>Your parent or guardian</strong>, where the institute has set up a parent account</li>
        <li><strong>Our hosting provider</strong> (Hostinger), which stores the data on servers on our behalf and may not use it for any other purpose</li>
    </ul>
    <p>We do not share your information with any other company. We would disclose it only if required by law.</p>

    <h2>5. Security and storage</h2>
    <p>All data travels between the app or website and our server over an encrypted (HTTPS) connection. Passwords are stored only in hashed form. Access to the server and database is restricted to the institute's administrators. The service is hosted on servers operated by Hostinger.</p>

    <h2>6. How long we keep it</h2>
    <p>We keep your account and results while you are enrolled and for up to 3 years after your course ends, so you can refer back to your results and the institute can meet its record-keeping duties. Technical logs are kept for up to 90 days. After that the data is deleted or anonymised.</p>

    <h2>7. Your rights</h2>
    <p>You can see and correct most of your information in the app or by asking the institute office. You can also ask us to:</p>
    <ul>
        <li>give you a copy of the information we hold about you,</li>
        <li>correct information that is wrong or out of date,</li>
        <li>delete your account and personal information (we may keep records the law requires us to keep),</li>
        <li>stop sending you non-essential messages.</li>
    </ul>
    <p>To make a request, email <a href="mailto:{{ config('mail.from.address') }}">{{ config('mail.from.address') }}</a> or speak to the institute office. We will respond within 30 days. If you are not satisfied with our response, you may complain to the Data Protection Board of India.</p>

    <h2>8. Account deletion</h2>
    <p>To delete your NOVA Z account and the personal information linked to it, email <a href="mailto:{{ config('mail.from.address') }}">{{ config('mail.from.address') }}</a> from your registered email address with the subject "Delete my account", or ask the institute office. Your account is deactivated immediately and the personal information is deleted within 30 days, except for records we must keep by law.</p>

    <h2>9. Changes to this policy</h2>
    <p>If we change this policy we will update the date at the top of this page and, for important changes, tell you in the app.</p>

